"""The repo is public. These checks keep out what can be recognised without naming it.

They hold no private term: a list of such terms would itself publish them. Reviewers check each
pull request for those terms from a list kept outside the repo.
"""
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
# The form of a Paperclip company id, and of most other generated ids.
UUID = re.compile(r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b", re.IGNORECASE)
LINK = re.compile(r"""https?://[^\s"'<>()\[\]`]+""")
# Hosts that docs and data may link to. A pull request that needs a new host adds it here.
LINK_HOSTS = {
    "github.com", "raw.githubusercontent.com", "microsoft.github.io", "agentcompanies.io",
    "www.aitmpl.com", "skills.sh", "code.claude.com", "developers.openai.com", "learn.chatgpt.com",
    "127.0.0.1", "json-schema.org", "nodejs.org",
}
LINKED_SUFFIXES = {".md", ".json", ".yml", ".yaml"}
# Generated by npm: every link in it is a package registry address.
NOT_LINK_CHECKED = {"frontend/package-lock.json"}


def tracked_files(root):
    listed = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True).stdout
    names = [name for name in listed.decode("utf-8").split("\0") if name]
    return {name: root / name for name in names if (root / name).is_file()}


def tree_files(root):
    return {path.relative_to(root).as_posix(): path for path in root.rglob("*") if path.is_file()}


def text_of(path):
    return path.read_bytes().decode("utf-8", errors="ignore")


def files_with_uuids(files):
    return {name: sorted(set(UUID.findall(text_of(path)))) for name, path in sorted(files.items())
            if UUID.search(text_of(path))}


def unlisted_link_hosts(files):
    found = {}
    for name, path in sorted(files.items()):
        if Path(name).suffix not in LINKED_SUFFIXES or name in NOT_LINK_CHECKED:
            continue
        hosts = {urlsplit(url).hostname for url in LINK.findall(text_of(path))}
        unlisted = sorted(host or "" for host in hosts if host not in LINK_HOSTS)
        if unlisted:
            found[name] = unlisted
    return found


class PublicContentTests(unittest.TestCase):
    maxDiff = None

    def test_no_tracked_file_contains_a_uuid(self):
        self.assertEqual(files_with_uuids(tracked_files(ROOT)), {})

    def test_docs_and_data_link_only_to_listed_hosts(self):
        self.assertEqual(unlisted_link_hosts(tracked_files(ROOT)), {})


class GuardOnTemporaryTreeTests(unittest.TestCase):
    """Each check passes on a copy of the tracked files and fails once a bad value is put in."""

    @classmethod
    def setUpClass(cls):
        cls._directory = tempfile.TemporaryDirectory()
        cls.tree = Path(cls._directory.name)
        for name, path in tracked_files(ROOT).items():
            target = cls.tree / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(path, target)
        cls.originals = {name: path.read_bytes() for name, path in tree_files(cls.tree).items()}

    @classmethod
    def tearDownClass(cls):
        cls._directory.cleanup()

    def tearDown(self):
        for name, data in self.originals.items():
            (self.tree / name).write_bytes(data)

    def append(self, name, text):
        path = self.tree / name
        path.write_bytes(path.read_bytes() + text.encode("utf-8"))

    def test_checks_pass_on_a_copy_of_the_tracked_files(self):
        files = tree_files(self.tree)
        self.assertEqual(files_with_uuids(files), {})
        self.assertEqual(unlisted_link_hosts(files), {})

    def test_a_uuid_in_any_file_fails(self):
        # Built from parts so that this file holds no UUID itself.
        uuid = "-".join(part * size for part, size in (("a", 8), ("b", 4), ("4", 4), ("8", 4), ("c", 12)))
        for name in ("README.md", "asm_app/store.py", "frontend/src/App.tsx"):
            with self.subTest(file=name):
                self.append(name, f"\ncompany {uuid.upper()}\n")
                self.assertEqual(files_with_uuids(tree_files(self.tree)), {name: [uuid.upper()]})
                self.tearDown()

    def test_a_link_to_an_unlisted_host_fails(self):
        for name, line in (("README.md", "\n[board](http://board.invalid/issues)\n"),
                           ("packages/cao/apm.yml", "\n# https://unlisted.invalid/repo\n"),
                           ("catalog/components.json", '\n"https://unlisted.invalid"\n')):
            with self.subTest(file=name):
                self.append(name, line)
                found = unlisted_link_hosts(tree_files(self.tree))
                self.assertEqual(list(found), [name])
                self.tearDown()

    def test_links_outside_docs_and_data_are_not_host_checked(self):
        self.append("asm_app/store.py", "\n# https://unlisted.invalid/\n")
        self.append("frontend/package-lock.json", "\n\"https://registry.npmjs.org/x\"\n")
        self.assertEqual(unlisted_link_hosts(tree_files(self.tree)), {})


if __name__ == "__main__":
    unittest.main()
